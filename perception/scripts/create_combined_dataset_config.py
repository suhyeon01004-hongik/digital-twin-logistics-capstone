#!/usr/bin/env python3
from __future__ import annotations

import argparse
from pathlib import Path

from path_config import DATA_ROOT


def parse_args():
    parser = argparse.ArgumentParser(
        description="Create a YOLO data.yaml that combines the original dataset and auto-collected samples."
    )
    parser.add_argument(
        "--original",
        default=str(DATA_ROOT / "processed" / "box_segmentation_yolo"),
    )
    parser.add_argument(
        "--auto",
        default=str(DATA_ROOT / "interim" / "auto_qr_box_seg"),
    )
    parser.add_argument(
        "--output",
        default=str(DATA_ROOT / "processed" / "combined_box_segmentation" / "data.yaml"),
    )
    parser.add_argument(
        "--include-auto-val",
        action="store_true",
        help="Include auto_qr_box_seg/val/images when it contains samples.",
    )
    return parser.parse_args()


def has_images(path: Path) -> bool:
    if not path.exists():
        return False
    return any(p.suffix.lower() in (".jpg", ".jpeg", ".png", ".bmp") for p in path.iterdir())


def yaml_list(paths: list[Path]) -> list[str]:
    return [f"  - {path}" for path in paths]


def main():
    args = parse_args()
    original = Path(args.original).expanduser()
    auto = Path(args.auto).expanduser()
    output = Path(args.output).expanduser()
    output.parent.mkdir(parents=True, exist_ok=True)

    train_paths = [
        original / "train" / "images",
        auto / "train" / "images",
    ]
    val_paths = [original / "valid" / "images"]
    auto_val = auto / "val" / "images"
    if args.include_auto_val and has_images(auto_val):
        val_paths.append(auto_val)

    text = "\n".join(
        [
            "# Generated by make_combined_dataset_yaml.py",
            "train:",
            *yaml_list(train_paths),
            "val:",
            *yaml_list(val_paths),
            "test:",
            f"  - {original / 'test' / 'images'}",
            "names:",
            "  0: box",
            "",
        ]
    )
    output.write_text(text, encoding="utf-8")
    print(output)


if __name__ == "__main__":
    main()
